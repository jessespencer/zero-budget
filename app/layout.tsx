import type { Metadata } from "next";
import { headers } from "next/headers";
import { Geist_Mono } from "next/font/google";
import "@fontsource-variable/figtree";
import { DevModeBanner } from "@/components/shared/dev-mode-banner";
import { PrivacyBanner } from "@/components/shared/privacy-banner";
import { PrivacyProvider } from "@/components/shared/privacy-provider";
import { ThemeProvider } from "@/components/shared/theme-provider";
import "./globals.css";

// Runs before first paint so a persisted "amounts hidden" state stamps <html>
// ahead of hydration — the globals.css blur rule then obscures server-rendered
// numbers until React swaps them to "$••••••". Mirrors next-themes' approach.
const antiFlashScript = `try{if(localStorage.getItem('zero-amounts-hidden')==='1'){document.documentElement.dataset.amountsHidden='1'}}catch(e){}`;

const geistMono = Geist_Mono({
  variable: "--font-geist-mono",
  subsets: ["latin"],
});

const TITLE = "Zero";
const DESCRIPTION = "Personal family finance";

// `og:image` has to be an absolute URL, and Next resolves the one generated by
// `app/opengraph-image.tsx` against `metadataBase`. Deriving that from the
// request host is what makes a LAN share work: the same build serves
// localhost:3000, a LAN IP and a Tailscale name, and each one
// advertises an image URL the previewing client can actually reach. A hardcoded
// base would point every preview at whichever host we guessed.
export async function generateMetadata(): Promise<Metadata> {
  const headerList = await headers();
  const host = headerList.get("host") ?? "localhost:3000";
  // LAN/Tailscale only — no TLS terminator in front of us, so http unless a
  // proxy says otherwise.
  const proto = headerList.get("x-forwarded-proto") ?? "http";

  const origin = `${proto}://${host}`;

  // The image is spelled out rather than left to the file-based
  // `app/opengraph-image.tsx` auto-population: that path resolves against the
  // server's own origin, not `metadataBase`, so a link shared from the Pi came
  // out advertising a localhost image that no other device can fetch. Naming
  // the absolute URL here is what actually makes the preview resolve.
  const image = {
    url: `${origin}/opengraph-image`,
    width: 1200,
    height: 630,
    alt: "Zero — Personal family finance",
    type: "image/png",
  };

  return {
    metadataBase: new URL(origin),
    title: TITLE,
    description: DESCRIPTION,
    applicationName: TITLE,
    openGraph: {
      type: "website",
      siteName: TITLE,
      title: TITLE,
      description: DESCRIPTION,
      url: origin,
      images: [image],
    },
    twitter: {
      card: "summary_large_image",
      title: TITLE,
      description: DESCRIPTION,
      images: [image],
    },
  };
}

export default function RootLayout({
  children,
}: Readonly<{
  children: React.ReactNode;
}>) {
  return (
    <html lang="en" suppressHydrationWarning>
      <body className={`${geistMono.variable} antialiased`}>
        <script dangerouslySetInnerHTML={{ __html: antiFlashScript }} />
        <ThemeProvider
          attribute="class"
          defaultTheme="system"
          enableSystem
          disableTransitionOnChange
        >
          <PrivacyProvider>
            <DevModeBanner />
            <PrivacyBanner />
            {children}
          </PrivacyProvider>
        </ThemeProvider>
      </body>
    </html>
  );
}
